ecozone_lookup <- function(ecoregion) {
  result  <- .ecozone_lookup_tbl[as.character(ecoregion)]
  missing <- ecoregion[is.na(result)]
  if (length(missing) > 0)
    stop("Ecoregion(s) not found in lookup table: ", paste(missing, collapse = ", "),
         ". Check ECOREGION values or update .ecozone_lookup_tbl in fct_ecozone_lookup.R.")
  unname(result)
}
